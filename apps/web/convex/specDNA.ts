function percent(done: number, total: number) {
  if (!total) return 0;
  return Math.round((done / total) * 100);
}

function readinessLane(label: string, items: any[], categories: string[]) {
  const scoped = items.filter((item) => categories.includes(item.category));
  const complete = scoped.filter((item) => item.status === "committed" || item.status === "resolved" || item.status === "rejected");
  const score = percent(complete.length, scoped.length);
  return {
    label,
    score,
    count: scoped.length,
    complete: complete.length,
    status: scoped.length === 0 ? "waiting" : score >= 90 ? "ready" : score >= 60 ? "needs review" : "at risk",
    blockers: scoped.filter((item) => item.status !== "committed" && item.status !== "resolved" && item.status !== "rejected").slice(0, 5).map((item) => item.title),
  };
}

