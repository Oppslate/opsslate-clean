function matchingSubcontractors(trade: string, subcontractors: any[]) {
  const normalizedTrade = trade.toLowerCase();
  return subcontractors
    .filter((sub) => {
      const haystack = [sub.trade, sub.name, sub.notes].filter(Boolean).join(" ").toLowerCase();
      return haystack.includes(normalizedTrade) || normalizedTrade.includes(String(sub.trade || "").toLowerCase());
    })
    .slice(0, 5)
    .map((sub) => ({
      subcontractorId: String(sub._id),
      company: sub.name,
      contact: sub.contactName,
      email: sub.email,
      phone: sub.phone,
      trade: sub.trade || trade,
      status: sub.status || "active",
    }));
}

