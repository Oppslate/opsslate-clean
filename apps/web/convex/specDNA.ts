export const commitApproved = mutation({
  args: { runId: v.id("specIntakeRuns") },
  handler: async (ctx, args) => {
    const a = (await import("./_generated/api")).api as any;
    const items = await ctx.db.query("specIntelligenceItems").withIndex("by_run", (q) => q.eq("runId", args.runId)).collect();
    let tasksCreated = 0;
    let submittalsCreated = 0;
    let rfisCreated = 0;
    let intelligenceCommitted = 0;

    for (const item of items) {
      if (item.status !== "approved" || item.createdRecordId) continue;
      if (item.category === "task") {
        const id = await createTaskFromSpecItem(ctx, item);
        await ctx.db.patch(item._id, { status: "committed", createdRecordType: "task", createdRecordId: String(id) });
        tasksCreated++;
      } else if (item.category === "submittal") {
        const id = await createSubmittalFromSpecItem(ctx, item);
        await ctx.db.patch(item._id, { status: "committed", createdRecordType: "submittal", createdRecordId: String(id) });
        submittalsCreated++;
      } else if (item.category === "risk") {
        const id = await createRfiFromSpecItem(ctx, item);
        await ctx.db.patch(item._id, { status: "committed", createdRecordType: "rfi", createdRecordId: String(id) });
        rfisCreated++;
      } else if (item.category === "schedule_driver") {
        const id = await createScheduleConstraintFromSpecItem(ctx, item);
        await ctx.db.patch(item._id, { status: "committed", createdRecordType: "schedule_constraint", createdRecordId: String(id) });
        intelligenceCommitted++;
      } else if (item.category === "billing_rule") {
        const id = await createPaymentRuleFromSpecItem(ctx, item);
        await ctx.db.patch(item._id, { status: "committed", createdRecordType: "payment_rule", createdRecordId: String(id) });
        intelligenceCommitted++;
      } else if (item.category === "bid_requirement" || item.category === "scope_item") {
        const id = await createEstimateRequirementFromSpecItem(ctx, item);
        await ctx.db.patch(item._id, { status: "committed", createdRecordType: "estimate_requirement", createdRecordId: String(id) });
        intelligenceCommitted++;
      } else {
        await ctx.db.patch(item._id, { status: "committed" });
        intelligenceCommitted++;
      }
    }
    await ctx.db.patch(args.runId, { status: "committed", committedAt: Date.now() });
    return { tasksCreated, submittalsCreated, rfisCreated, intelligenceCommitted };
  },
});

