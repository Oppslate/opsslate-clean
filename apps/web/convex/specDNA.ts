function normalizeObligationText(item: any) {
  return [item.title, item.description, item.sourceQuote]
    .filter(Boolean)
    .join(" ")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\b(the|and|or|shall|must|required|provide|include|includes|section|spec)\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function obligationFingerprint(item: any) {
  return normalizeObligationText(item).split(" ").filter((word) => word.length > 3).slice(0, 12).join(" ");
}

function relatedObligations(a: any, b: any) {
  return Boolean(
    (a.specSection && b.specSection && a.specSection === b.specSection) ||
    (a.trade && b.trade && a.trade === b.trade) ||
    (a.phase && b.phase && a.phase === b.phase)
  );
}

function detectDuplicateSignals(items: any[]) {
  const groups: Record<string, any[]> = {};
  for (const item of items) {
    const fingerprint = obligationFingerprint(item);
    if (fingerprint.length < 18) continue;
    const key = `${item.category}:${item.specSection || "no-section"}:${fingerprint}`;
    groups[key] = [...(groups[key] || []), item];
  }
  return Object.values(groups)
    .filter((group) => group.length > 1)
    .slice(0, 10)
    .map((group) => ({
      title: group[0].title,
      reason: `${group.length} similar ${group[0].category.replace(/_/g, " ")} obligations found`,
      priority: "Medium",
      itemIds: group.map((item) => String(item._id)),
      sourceSpecSection: group[0].specSection,
      sourceQuote: group[0].sourceQuote,
    }));
}

function contradictionPair(textA: string, textB: string) {
  const pairs = [
    [/include|included|includes/, /exclude|excluded|excludes|not included/],
    [/required|mandatory|shall|must/, /optional|if required|when directed/],
    [/\byes\b|required/, /\bno\b|not required/],
    [/before|prior to/, /after|following/],
    [/contractor|gc|general contractor/, /owner|by others/],
  ];
  return pairs.some(([left, right]) => (left.test(textA) && right.test(textB)) || (right.test(textA) && left.test(textB)));
}

function detectConflictSignals(items: any[]) {
  const signals: any[] = [];
  for (let i = 0; i < items.length; i++) {
    for (let j = i + 1; j < items.length; j++) {
      const first = items[i];
      const second = items[j];
      if (!relatedObligations(first, second)) continue;
      const firstText = normalizeObligationText(first);
      const secondText = normalizeObligationText(second);
      if (!contradictionPair(firstText, secondText)) continue;
      signals.push({
        title: first.specSection ? `Possible conflict in ${first.specSection}` : "Possible spec conflict",
        reason: `${first.title} may conflict with ${second.title}`,
        priority: first.priority === "Critical" || second.priority === "Critical" ? "Critical" : "High",
        rfiRecommended: true,
        itemIds: [String(first._id), String(second._id)],
        sourceSpecSection: first.specSection || second.specSection,
        sourceQuote: [first.sourceQuote, second.sourceQuote].filter(Boolean).join(" / ").slice(0, 900),
      });
      if (signals.length >= 12) return signals;
    }
  }
  return signals;
}

function clampScore(value: number) {
  return Math.max(0, Math.min(100, Math.round(value)));
}

function sourceQualityScore(item: any) {
  let score = Math.round((item.confidence ?? 0.55) * 55);
  if (item.sourceQuote && String(item.sourceQuote).length >= 80) score += 18;
  else if (item.sourceQuote) score += 10;
  if (item.specSection) score += 14;
  if (item.sourcePage) score += 5;
  if (item.description && String(item.description).length >= 40) score += 8;
  return clampScore(score);
}

function duplicateEvidenceScore(item: any, duplicateSignals: any[]) {
  const duplicate = duplicateSignals.find((signal) => (signal.itemIds || []).includes(String(item._id)));
  if (!duplicate) return 72;
  const count = duplicate.itemIds?.length || 2;
  return clampScore(80 + Math.min(count, 5) * 4);
}

function contradictionRiskScore(item: any, conflictSignals: any[]) {
  const conflict = conflictSignals.find((signal) => (signal.itemIds || []).includes(String(item._id)));
  if (!conflict) return 92;
  if (conflict.priority === "Critical") return 20;
  if (conflict.priority === "High") return 35;
  return 55;
}

function downstreamReadinessScore(item: any) {
  if (item.status === "resolved" || item.closedLoopSyncedAt) return 100;
  if (item.createdRecordId && item.status === "committed") return 90;
  if (item.createdRecordId) return 82;
  if (item.status === "approved") return 62;
  if (item.status === "rejected") return 75;
  if (item.status === "draft") return 35;
  return 50;
}

function confidenceBand(score: number) {
  if (score >= 85) return "High";
  if (score >= 65) return "Medium";
  if (score >= 45) return "Watch";
  return "Low";
}

function buildConfidenceScoringV2(items: any[], duplicateSignals: any[], conflictSignals: any[]) {
  const rows = items.map((item) => {
    const sourceQuality = sourceQualityScore(item);
    const duplicateEvidence = duplicateEvidenceScore(item, duplicateSignals);
    const contradictionRisk = contradictionRiskScore(item, conflictSignals);
    const downstreamReadiness = downstreamReadinessScore(item);
    const score = clampScore(
      sourceQuality * 0.38 +
      duplicateEvidence * 0.16 +
      contradictionRisk * 0.24 +
      downstreamReadiness * 0.22
    );
    const scoreDrivers = [
      sourceQuality < 60 ? "Weak source evidence" : "Source evidence is traceable",
      duplicateEvidence >= 85 ? "Duplicate clauses support this obligation" : "No duplicate support found",
      contradictionRisk < 70 ? "Contradiction risk needs review" : "No contradiction detected",
      downstreamReadiness >= 85 ? "Downstream workflow is committed or resolved" : "Downstream workflow is not fully ready",
    ];
    return {
      itemId: String(item._id),
      title: item.title,
      category: item.category,
      status: item.status,
      sourceQuality,
      duplicateEvidence,
      contradictionRisk,
      downstreamReadiness,
      score,
      confidenceBand: confidenceBand(score),
      scoreDrivers,
      sourceSpecSection: item.specSection,
      sourceQuote: item.sourceQuote,
    };
  }).sort((a, b) => a.score - b.score);

  const averageScore = rows.length ? clampScore(rows.reduce((sum, row) => sum + row.score, 0) / rows.length) : 100;
  return {
    averageScore,
    highConfidence: rows.filter((row) => row.confidenceBand === "High").length,
    watchItems: rows.filter((row) => row.confidenceBand === "Watch" || row.confidenceBand === "Low").length,
    lowConfidence: rows.filter((row) => row.confidenceBand === "Low").length,
    rows: rows.slice(0, 12),
  };
}

