function buildExceptionDashboard(args: { runs: any[]; items: any[]; conflictSignals: any[]; duplicateSignals: any[] }) {
  const failedRuns = args.runs
    .filter((run) => run.status === "failed")
    .map((run) => exceptionRow("failed_run", run.sourceDocumentName, "Critical", "Project admin", { status: run.status }, run.error));
  const lowConfidence = args.items
    .filter((item) => (item.confidence || 0) < 0.55 && item.status !== "rejected")
    .map((item) => exceptionRow("low_confidence", item.title, (item.confidence || 0) < 0.4 ? "High" : "Medium", "Estimator / PM", item, "Review extracted source evidence before committing"));
  const missingDestination = args.items
    .filter((item) => !item.createdRecordId && item.status === "committed")
    .map((item) => exceptionRow("missing_destination", item.title, "High", "PM", item, "Marked committed without a linked downstream record"));
  const approvedNotCommitted = args.items
    .filter((item) => item.status === "approved" && !item.createdRecordId)
    .map((item) => exceptionRow("approved_not_committed", item.title, "Medium", "PM", item, "Approved item is ready but has not been pushed downstream"));
  const conflictExceptions = args.conflictSignals.map((item) => exceptionRow("conflict", item.title, item.priority || "High", "PM / Estimator", item, item.reason));
  const duplicateExceptions = args.duplicateSignals.map((item) => exceptionRow("duplicate", item.title, item.priority || "Medium", "Spec reviewer", item, item.reason));
  const rows = [...failedRuns, ...conflictExceptions, ...missingDestination, ...approvedNotCommitted, ...lowConfidence, ...duplicateExceptions].slice(0, 30);

  return {
    total: rows.length,
    critical: rows.filter((row) => row.severity === "Critical").length,
    high: rows.filter((row) => row.severity === "High").length,
    medium: rows.filter((row) => row.severity === "Medium").length,
    byType: {
      failed_run: failedRuns.length,
      low_confidence: lowConfidence.length,
      missing_destination: missingDestination.length,
      approved_not_committed: approvedNotCommitted.length,
      conflict: conflictExceptions.length,
      duplicate: duplicateExceptions.length,
    },
    rows,
  };
}

