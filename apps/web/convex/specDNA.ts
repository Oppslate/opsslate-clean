export const analyzeSpecDocument = action({
  args: {
    companyId: v.id("companies"),
    projectId: v.id("projects"),
    documentId: v.id("documents"),
    createdBy: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const a = (await import("./_generated/api")).api as any;
    const doc = await ctx.runQuery(a.docManager.getById, { id: args.documentId });
    if (!doc) throw new Error("Document not found");
    const runId = await ctx.runMutation(a.specDNA.createRunInternal, {
      companyId: args.companyId,
      projectId: args.projectId,
      sourceDocumentId: args.documentId,
      sourceDocumentName: doc.name,
      createdBy: args.createdBy,
    });

    try {
      const storageKey = doc.storageId || doc.fileId;
      if (!storageKey) throw new Error("No storage file found for this document");
      const url = await ctx.storage.getUrl(storageKey);
      if (!url) throw new Error("Spec file not found in storage");
      const response = await fetch(url);
      const buffer = await response.arrayBuffer();
      const text = compactText(new TextDecoder("utf-8", { fatal: false }).decode(buffer)).slice(0, 140000);
      if (text.length < 500) throw new Error("Could not extract enough readable text from this spec. Try a text-based PDF for phase one.");

      const prompt = `You are OpsSlate SpecDNA, a construction bid-to-build obligation graph engine.

Read the specification text and extract operational obligations. Return valid JSON only:
{
  "summary": "short operational summary",
  "items": [
    {
      "category": "bid_requirement | scope_item | submittal | task | schedule_driver | billing_rule | risk",
      "title": "concise title",
      "description": "what is required",
      "trade": "trade or null",
      "phase": "phase or null",
      "priority": "Critical | High | Medium | Low",
      "confidence": 0.0,
      "specSection": "section number/name or null",
      "sourcePage": "page reference if visible or null",
      "sourceQuote": "short quote that proves the requirement",
      "destinationModules": ["estimating", "pm", "submittals", "schedule", "billing", "rfi"],
      "suggestedRecord": {},
      "relationships": []
    }
  ]
}

Extract these categories:
- Bid Requirements: bid date, DBE, wage, bonding, insurance, liquidated damages, contract days, alternates, allowances.
- Scope Items: trade scope, material requirements, installation requirements, estimate-impacting work.
- Submittals: shop drawings, product data, samples, certifications, warranties, test reports.
- Project Tasks: permits, notices, meetings, inspections, testing, startup, owner training, closeout.
- Schedule Drivers: review durations, lead times, sequencing, hold points, milestones.
- Billing Rules: measurement/payment language, unit price rules, stored material rules, retainage, backup docs, certified payroll.
- Risks / RFIs: ambiguous, conflicting, missing, unusually strict, or high-cost requirements.

Rules:
- Extract obligations, not generic summaries.
- Do not invent dates, quantities, or sections.
- Include sourceQuote whenever possible.
- destinationModules should describe where OpsSlate should use the item.
- Use lower confidence when evidence is weak.

SPEC DOCUMENT: ${doc.name}

SPEC TEXT:
${text}`;

      const apiKey = process.env.ANTHROPIC_API_KEY;
      if (!apiKey) throw new Error("ANTHROPIC_API_KEY not set");
      let parsed;
      try {
        const raw = await callClaude(apiKey, prompt);
        parsed = extractJson(raw);
      } catch (aiError: any) {
        const message = aiError?.message || "";
        if (!isRecoverableAiFailure(message)) throw new Error(cleanAiError(message));
        const openAiKey = process.env.OPENAI_API_KEY;
        const openRouterKey = process.env.OPENROUTER_API_KEY;
        if (openAiKey) {
          try {
            const raw = await callOpenAI(openAiKey, prompt);
            parsed = extractJson(raw);
          } catch (openAiError: any) {
            if (!isRecoverableAiFailure(openAiError?.message || "")) throw new Error(cleanAiError(openAiError?.message || ""));
            if (openRouterKey) {
              const raw = await callOpenRouter(openRouterKey, prompt);
              parsed = extractJson(raw);
            } else {
              parsed = buildFallbackSpecMatrix(text, doc.name);
            }
          }
        } else if (openRouterKey) {
          const raw = await callOpenRouter(openRouterKey, prompt);
          parsed = extractJson(raw);
        } else {
          parsed = buildFallbackSpecMatrix(text, doc.name);
        }
      }
      await ctx.runMutation(a.specDNA.replaceRunItemsInternal, {
        runId,
        companyId: args.companyId,
        projectId: args.projectId,
        sourceDocumentId: args.documentId,
        summary: parsed.summary || "",
        items: Array.isArray(parsed.items) ? parsed.items : [],
      });
      return { runId, items: Array.isArray(parsed.items) ? parsed.items.length : 0 };
    } catch (err: any) {
      const message = cleanAiError(err?.message || "SpecDNA analysis failed");
      await ctx.runMutation(a.specDNA.markRunFailedInternal, { runId, error: message });
      throw new Error(message);
    }
  },
});
