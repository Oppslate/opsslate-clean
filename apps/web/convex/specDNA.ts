function contactMatches(contact: any, name?: string) {
  const needle = String(name || "").toLowerCase().trim();
  if (!needle) return false;
  const haystack = [contact.firstName, contact.lastName, contact.name, contact.company, contact.email]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
  const company = String(contact.company || "").toLowerCase().trim();
  return haystack.includes(needle) || Boolean(company && needle.includes(company));
}

function resolveReminderRecipient(recordType: string, record: any, contacts: any[]) {
  if (recordType === "submittal" || recordType === "subcontractor_request") {
    return {
      name: record.responsibleContact || record.responsibleCompany || record.reviewer,
      email: record.responsibleEmail,
      phone: record.responsiblePhone,
    };
  }
  const owner = record.assignedTo || record.ballInCourt || record.requestedBy;
  const contact = contacts.find((candidate) => contactMatches(candidate, owner));
  return {
    name: owner || contact?.firstName || contact?.name,
    email: contact?.email,
    phone: contact?.phone,
  };
}

