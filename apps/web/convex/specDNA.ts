const CATEGORIES = ["bid_requirement", "scope_item", "submittal", "task", "schedule_driver", "billing_rule", "risk"];

function normalizeCategory(value: unknown) {
  const category = String(value || "").trim().toLowerCase();
  return CATEGORIES.includes(category) ? category : "scope_item";
}

function extractJson(raw: string) {
  const start = raw.indexOf("{");
  const end = raw.lastIndexOf("}");
  if (start < 0 || end < start) return { summary: "", items: [] };
  return JSON.parse(raw.slice(start, end + 1));
}

function compactText(text: string) {
  return text.replace(/[^\x20-\x7E\n\r\t]/g, " ").replace(/\s{3,}/g, " ").trim();
}

function isRecoverableAiFailure(message: string) {
  return /credit balance|billing|rate limit|overloaded|temporarily unavailable|timeout|Claude API error/i.test(message);
}

function cleanAiError(message: string) {
  if (/credit balance|billing/i.test(message)) return "AI provider billing is unavailable. Check the configured AI provider account balance or run the fallback matrix.";
  return message || "Spec Intelligence Intake Matrix analysis failed.";
}

function firstMatch(value: string, patterns: RegExp[]) {
  return patterns.some((pattern) => pattern.test(value));
}

function specSectionFromLine(line: string) {
  return line.match(/\b(?:section|spec(?:ification)?\s*section)?\s*(\d{2}\s*\d{2}\s*\d{2}|\d{5,6}|\d{2}\s+\d{2}\s+\d{2})\b/i)?.[1]?.replace(/\s+/g, " ");
}

function buildFallbackSpecMatrix(text: string, documentName: string) {
  const rules = [
    {
      category: "submittal",
      title: "Submittal requirement",
      destinationModules: ["pm", "submittals", "schedule"],
      patterns: [/submittal/i, /shop drawing/i, /product data/i, /sample/i, /certification/i, /test report/i, /warrant/i, /mix design/i],
    },
    {
      category: "bid_requirement",
      title: "Bid requirement",
      destinationModules: ["estimating", "pm"],
      patterns: [/bid date/i, /letting/i, /bond/i, /insurance/i, /prevailing wage/i, /\bDBE\b|\bMBE\b|\bWBE\b/i, /liquidated damages/i, /allowance/i, /alternate/i, /unit price/i],
    },
    {
      category: "billing_rule",
      title: "Billing or payment rule",
      destinationModules: ["billing", "pm"],
      patterns: [/measurement/i, /payment/i, /retainage/i, /stored material/i, /certified payroll/i, /pay item/i, /backup documentation/i],
    },
    {
      category: "schedule_driver",
      title: "Schedule driver",
      destinationModules: ["schedule", "pm"],
      patterns: [/lead time/i, /sequence/i, /milestone/i, /calendar day/i, /working day/i, /review period/i, /approval period/i, /prior to/i, /before proceeding/i],
    },
    {
      category: "risk",
      title: "Clarification risk",
      destinationModules: ["rfi", "estimating", "pm"],
      patterns: [/verify/i, /conflict/i, /coordinate/i, /as directed/i, /or equal/i, /field condition/i, /unknown/i, /clarification/i],
    },
    {
      category: "task",
      title: "Project task",
      destinationModules: ["pm", "schedule"],
      patterns: [/permit/i, /notify/i, /inspection/i, /testing/i, /startup/i, /training/i, /closeout/i, /submit/i, /coordinate/i],
    },
    {
      category: "scope_item",
      title: "Scope requirement",
      destinationModules: ["estimating", "pm"],
      patterns: [/provide/i, /install/i, /furnish/i, /construct/i, /remove/i, /replace/i, /material/i, /equipment/i],
    },
  ];

  const seen = new Set<string>();
  const lines = text.split(/\n|(?<=\.)\s+/).map((line) => line.replace(/\s+/g, " ").trim()).filter((line) => line.length >= 35 && line.length <= 700);
  const items: any[] = [];

  for (const line of lines) {
    if (items.length >= 80) break;
    const normalized = line.toLowerCase();
    if (seen.has(normalized)) continue;
    const rule = rules.find((candidate) => firstMatch(line, candidate.patterns));
    if (!rule) continue;
    seen.add(normalized);
    const specSection = specSectionFromLine(line);
    items.push({
      category: rule.category,
      title: specSection ? `${rule.title} - ${specSection}` : rule.title,
      description: line.slice(0, 500),
      priority: rule.category === "risk" || rule.category === "bid_requirement" ? "High" : "Medium",
      confidence: 0.42,
      specSection,
      sourceQuote: line.slice(0, 700),
      destinationModules: rule.destinationModules,
      notes: "Generated by the local fallback extractor because the AI provider is unavailable.",
    });
  }

  return {
    summary: `AI provider is unavailable, so OpsSlate created a rules-based fallback matrix from ${documentName}. Review carefully, then rerun the AI matrix after the provider account is funded.`,
    items,
  };
}

function openaiTextFromResponse(result: any) {
  if (typeof result.output_text === "string") return result.output_text;
  const text: string[] = [];
  for (const item of result.output || []) {
    for (const content of item.content || []) {
      if (content.type === "output_text" && typeof content.text === "string") text.push(content.text);
      if (content.type === "text" && typeof content.text === "string") text.push(content.text);
    }
  }
  return text.join("\n");
}

async function callClaude(apiKey: string, prompt: string) {
  const response = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: { "Content-Type": "application/json", "x-api-key": apiKey, "anthropic-version": "2023-06-01" },
    body: JSON.stringify({
      model: "claude-sonnet-4-20250514",
      max_tokens: 12000,
      messages: [{ role: "user", content: [{ type: "text", text: prompt }] }],
    }),
  });
  if (!response.ok) throw new Error(`Claude API error: ${await response.text()}`);
  const result = await response.json();
  return result.content?.[0]?.text || "{}";
}

