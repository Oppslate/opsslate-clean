function impactSeverity(change: any, impactedRecords: any[]) {
  const highRiskText = [change.title, change.sourceQuote].filter(Boolean).join(" ");
  let severityScore = impactedRecords.length * 12;
  if (change.category === "risk" || /liquidated damages|bid date|bond|insurance|exclusion|allowance|alternate|unit price/i.test(highRiskText)) severityScore += 35;
  if (change.category === "bid_requirement" || change.category === "billing_rule") severityScore += 20;
  if (change.changeType === "removed" || change.changeType === "changed") severityScore += 15;
  const severity = severityScore >= 70 ? "Critical" : severityScore >= 45 ? "High" : severityScore >= 20 ? "Medium" : "Low";
  return { severity, severityScore: Math.min(100, severityScore) };
}

function impactRecommendedAction(change: any, affectedModules: string[]) {
  if (affectedModules.includes("rfi")) return "Create or update an RFI with the changed spec evidence.";
  if (affectedModules.includes("estimate_items")) return "Review pricing, alternates, exclusions, and estimate assumptions before bid lock.";
  if (affectedModules.includes("bid_packages")) return "Revise affected scope sheets and notify invited subcontractors.";
  if (affectedModules.includes("submittals")) return "Update the submittal register and responsible subcontractor request path.";
  if (affectedModules.includes("schedule")) return "Review predecessor/successor logic and milestone dates.";
  if (affectedModules.includes("billing")) return "Update pay-app checklist rules and backup documentation.";
  return `Review ${change.changeType} spec change before committing downstream.`;
}

function buildSpecChangeImpactEngine(args: {
  addendaDelta: any;
  items: any[];
  rfis: any[];
  tasks: any[];
  submittals: any[];
  scheduleConstraints: any[];
  paymentRules: any[];
  estimateRequirements: any[];
  bidPackageIntelligence: any;
}) {
  const changes = [
    ...(args.addendaDelta?.addedItems || []).map((item: any) => ({ ...item, changeType: "added" })),
    ...(args.addendaDelta?.changedItems || []).map((item: any) => ({ ...item, changeType: "changed" })),
    ...(args.addendaDelta?.removedItems || []).map((item: any) => ({ ...item, changeType: "removed" })),
    ...(args.addendaDelta?.newRiskItems || []).map((item: any) => ({ ...item, changeType: "new_risk" })),
  ];

  const impacts = changes.slice(0, 16).map((change: any) => {
    const specSection = change.sourceSpecSection || change.specSection;
    const affectedModules = new Set<string>();
    const impactedRecords: any[] = [];
    const matchesSection = (record: any) => specSection && (record.sourceSpecSection === specSection || record.specSection === specSection);

    const rfiMatches = args.rfis.filter(matchesSection);
    if (rfiMatches.length || change.category === "risk") {
      affectedModules.add("rfi");
      impactedRecords.push(...rfiMatches.slice(0, 3).map((record) => ({ module: "rfi", recordId: String(record._id), title: record.subject || "RFI" })));
    }

    const taskMatches = args.tasks.filter(matchesSection);
    if (taskMatches.length || change.category === "task") {
      affectedModules.add("tasks");
      impactedRecords.push(...taskMatches.slice(0, 3).map((record) => ({ module: "tasks", recordId: String(record._id), title: record.customTask || record.task || "Task" })));
    }

    const submittalMatches = args.submittals.filter(matchesSection);
    if (submittalMatches.length || change.category === "submittal") {
      affectedModules.add("submittals");
      affectedModules.add("subcontractor_notifications");
      impactedRecords.push(...submittalMatches.slice(0, 3).map((record) => ({ module: "submittals", recordId: String(record._id), title: record.title || record.description || "Submittal" })));
    }

    const scheduleMatches = args.scheduleConstraints.filter(matchesSection);
    if (scheduleMatches.length || change.category === "schedule_driver") {
      affectedModules.add("schedule");
      impactedRecords.push(...scheduleMatches.slice(0, 3).map((record) => ({ module: "schedule", recordId: String(record._id), title: record.title || "Schedule constraint" })));
    }

    const billingMatches = args.paymentRules.filter(matchesSection);
    if (billingMatches.length || change.category === "billing_rule") {
      affectedModules.add("billing");
      impactedRecords.push(...billingMatches.slice(0, 3).map((record) => ({ module: "billing", recordId: String(record._id), title: record.title || "Payment rule" })));
    }

    const estimateMatches = args.estimateRequirements.filter(matchesSection);
    if (estimateMatches.length || change.category === "bid_requirement" || change.category === "scope_item") {
      affectedModules.add("estimate_items");
      impactedRecords.push(...estimateMatches.slice(0, 3).map((record) => ({ module: "estimate_items", recordId: String(record._id), title: record.title || "Estimate requirement" })));
    }

    const packageMatches = (args.bidPackageIntelligence?.scopeSheets || []).filter((sheet: any) => sheet.sourceEvidence?.some((source: any) => source.sourceSpecSection === specSection));
    if (packageMatches.length || change.category === "scope_item" || change.category === "bid_requirement" || change.category === "submittal") {
      affectedModules.add("bid_packages");
      impactedRecords.push(...packageMatches.slice(0, 3).map((sheet: any) => ({ module: "bid_packages", recordId: sheet.packageName, title: sheet.packageName })));
    }

    const severity = impactSeverity(change, impactedRecords);
    const modules = Array.from(affectedModules);
    return {
      changeType: change.changeType,
      title: change.title || "Spec change",
      category: change.category,
      affectedModules: modules,
      impactedRecords,
      recommendedAction: impactRecommendedAction(change, modules),
      severity: severity.severity,
      severityScore: severity.severityScore,
      sourceEvidence: packageEvidence(change),
    };
  }).sort((first, second) => second.severityScore - first.severityScore);

  return {
    status: impacts.some((item) => item.severity === "Critical" || item.severity === "High") ? "action_required" : impacts.length ? "review_changes" : "clear",
    totalChanges: changes.length,
    highImpact: impacts.filter((item) => item.severity === "Critical" || item.severity === "High").length,
    downstreamRecordsAffected: impacts.reduce((sum, item) => sum + item.impactedRecords.length, 0),
    modulesAffected: Array.from(new Set(impacts.flatMap((item) => item.affectedModules))),
    impacts,
  };
}

function deltaKey(item: any) {
  const section = item.specSection || "no-section";
  const fingerprint = obligationFingerprint(item) || normalizeObligationText(item).slice(0, 80);
  return `${section}:${fingerprint}`;
}

function slimDeltaItem(item: any) {
  return {
    id: String(item._id),
    title: item.title,
    category: item.category,
    priority: item.priority || "Medium",
    status: item.status,
    sourceSpecSection: item.specSection,
    sourceQuote: item.sourceQuote,
  };
}

function buildAddendaDelta(runs: any[], items: any[]) {
  const latest = runs[0];
  const previous = runs[1];
  if (!latest || !previous) {
    return {
      hasComparison: false,
      latestRunId: latest ? String(latest._id) : undefined,
      previousRunId: undefined,
      changeSummary: "Run another spec intake to compare addenda or revised spec books.",
      addedItems: [],
      removedItems: [],
      changedItems: [],
      newRiskItems: [],
    };
  }

  const latestItems = items.filter((item) => String(item.runId) === String(latest._id));
  const previousItems = items.filter((item) => String(item.runId) === String(previous._id));
  const latestByKey = new Map(latestItems.map((item) => [deltaKey(item), item]));
  const previousByKey = new Map(previousItems.map((item) => [deltaKey(item), item]));

  const addedItems = latestItems.filter((item) => !previousByKey.has(deltaKey(item))).slice(0, 12).map(slimDeltaItem);
  const removedItems = previousItems.filter((item) => !latestByKey.has(deltaKey(item))).slice(0, 12).map(slimDeltaItem);
  const changedItems = latestItems
    .filter((item) => {
      const previousItem = previousByKey.get(deltaKey(item));
      return previousItem && (
        previousItem.category !== item.category ||
        previousItem.priority !== item.priority ||
        previousItem.status !== item.status ||
        previousItem.sourceQuote !== item.sourceQuote
      );
    })
    .slice(0, 12)
    .map((item) => ({ ...slimDeltaItem(item), previousCategory: previousByKey.get(deltaKey(item))?.category, previousPriority: previousByKey.get(deltaKey(item))?.priority }));
  const newRiskItems = addedItems.filter((item) => item.category === "risk");

  return {
    hasComparison: true,
    latestRunId: String(latest._id),
    previousRunId: String(previous._id),
    latestSource: latest.sourceDocumentName,
    previousSource: previous.sourceDocumentName,
    changeSummary: `${addedItems.length} new, ${removedItems.length} removed, ${changedItems.length} changed, and ${newRiskItems.length} new risk obligations since the prior intake.`,
    addedItems,
    removedItems,
    changedItems,
    newRiskItems,
  };
}

const DAY_MS = 24 * 60 * 60 * 1000;

function dateOnlyTime(value: Date) {
  return Date.UTC(value.getUTCFullYear(), value.getUTCMonth(), value.getUTCDate());
}

function parseDateOnly(value?: string) {
  if (!value) return undefined;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return undefined;
  return dateOnlyTime(date);
}

function daysUntil(value?: string) {
  const target = parseDateOnly(value);
  if (target === undefined) return undefined;
  return Math.round((target - dateOnlyTime(new Date())) / DAY_MS);
}

function reminderStatus(value?: string) {
  const days = daysUntil(value);
  if (days === undefined) return "unscheduled";
  if (days < 0) return "overdue";
  if (days === 0) return "due_today";
  if (days <= 7) return "due_soon";
  return "upcoming";
}

function reminderPriority(status: string, fallback?: string) {
  if (status === "overdue") return "High";
  if (status === "due_today") return "High";
  if (status === "due_soon") return fallback || "Medium";
  if (status === "unscheduled") return fallback || "Medium";
  return fallback || "Low";
}

function activeStatus(value?: string) {
  const status = String(value || "").toLowerCase();
  return !/(closed|complete|approved|answered|resolved|rejected)/.test(status);
}

function reminderRow(recordType: string, record: any, title: string | undefined, dueDate: string | undefined, owner: string | undefined, reason?: string) {
  const status = reminderStatus(dueDate);
  return {
    recordType,
    recordId: String(record._id),
    title: title || "Follow-up needed",
    owner: owner || "Unassigned",
    email: record.responsibleEmail,
    phone: record.responsiblePhone,
    dueDate,
    status,
    daysUntil: daysUntil(dueDate),
    reason: reason || (
      status === "overdue" ? "Overdue follow-up" :
      status === "due_today" ? "Due today" :
      status === "due_soon" ? "Due soon" :
      "Needs owner or due date"
    ),
    priority: reminderPriority(status, record.priority),
    lastReminderSentAt: record.lastReminderSentAt,
    reminderCount: record.reminderCount || 0,
    lastReminderChannel: record.lastReminderChannel,
    lastReminderStatus: record.lastReminderStatus,
    lastReminderMessageId: record.lastReminderMessageId,
    lastReminderError: record.lastReminderError,
    sourceSpecSection: record.sourceSpecSection || record.specSection,
    sourceQuote: record.sourceQuote,
  };
}

function reminderShouldShow(row: any) {
  return row.status === "overdue" || row.status === "due_today" || row.status === "due_soon" || row.owner === "Unassigned";
}

function buildReminderQueue(args: { rfis: any[]; tasks: any[]; submittals: any[] }) {
  const rows = [
    ...args.submittals
      .filter((item) => activeStatus(item.status))
      .flatMap((item) => {
        const base = reminderRow("submittal", item, item.title, item.dueDate || item.dateRequired, item.responsibleCompany || item.responsibleContact || item.reviewer);
        const subcontractorRequest = item.responsibleEmail && !/(received|approved|closed)/i.test(String(item.requestStatus || ""))
          ? reminderRow("subcontractor_request", item, item.title, item.dueDate || item.dateRequired, item.responsibleCompany || item.responsibleContact, "Subcontractor submittal request needs follow-up")
          : null;
        return [base, subcontractorRequest].filter(Boolean);
      }),
    ...args.rfis
      .filter((item) => activeStatus(item.status))
      .map((item) => reminderRow("rfi", item, item.subject, item.dateRequired || item.responseRequired, item.assignedTo || item.ballInCourt, "RFI answer or assignment needs follow-up")),
    ...args.tasks
      .filter((item) => activeStatus(item.status))
      .map((item) => reminderRow("task", item, item.customTask || item.task, item.dateScheduled || item.dateOrdered, item.assignedTo, !item.assignedTo ? "Task owner missing" : "Task due-date follow-up needed")),
  ].filter(Boolean).filter(reminderShouldShow);

  return rows.sort((first: any, second: any) => {
    const rank: Record<string, number> = { overdue: 0, due_today: 1, due_soon: 2, unscheduled: 3, upcoming: 4 };
    const firstRank = rank[first.status] ?? 9;
    const secondRank = rank[second.status] ?? 9;
    if (firstRank !== secondRank) return firstRank - secondRank;
    return (first.daysUntil ?? 999) - (second.daysUntil ?? 999);
  }).slice(0, 24);
}

