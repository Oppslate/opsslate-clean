async function sendResendReminder(target: any) {
  const resendKey = process.env.RESEND_API_KEY;
  if (!resendKey) return { sent: false, status: "not_configured", error: "RESEND_API_KEY not set" };
  if (!target.recipient?.email) return { sent: false, status: "missing_recipient", error: "No email address found for reminder target" };
  const response = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${resendKey}` },
    body: JSON.stringify({
      from: emailFrom("OpsSlate Reminders"),
      reply_to: emailReplyTo(),
      to: [target.recipient.email],
      subject: target.subject,
      text: target.body,
    }),
  });
  if (!response.ok) return { sent: false, status: "failed", error: await response.text() };
  const result = await response.json();
  return { sent: true, status: "sent", messageId: result.id };
}

async function sendTwilioReminder(target: any) {
  const accountSid = process.env.TWILIO_ACCOUNT_SID;
  const authToken = process.env.TWILIO_AUTH_TOKEN;
  const messagingServiceSid = process.env.TWILIO_MESSAGING_SERVICE_SID;
  const from = process.env.TWILIO_FROM_NUMBER;
  if (!accountSid || !authToken || (!messagingServiceSid && !from)) {
    return { sent: false, status: "not_configured", error: "Twilio SMS is not configured" };
  }
  if (!target.recipient?.phone) return { sent: false, status: "missing_recipient", error: "No phone number found for reminder target" };
  const params = new URLSearchParams({
    To: target.recipient.phone,
    Body: target.body.slice(0, 1500),
  });
  if (messagingServiceSid) params.set("MessagingServiceSid", messagingServiceSid);
  else params.set("From", from!);
  const auth = btoa(`${accountSid}:${authToken}`);
  const response = await fetch(`https://api.twilio.com/2010-04-01/Accounts/${accountSid}/Messages.json`, {
    method: "POST",
    headers: { Authorization: `Basic ${auth}`, "Content-Type": "application/x-www-form-urlencoded" },
    body: params,
  });
  const text = await response.text();
  if (!response.ok) return { sent: false, status: "failed", error: text };
  const result = JSON.parse(text);
  return { sent: true, status: "sent", messageId: result.sid };
}

